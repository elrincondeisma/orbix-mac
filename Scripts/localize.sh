#!/usr/bin/env bash
# Keeps the translations in step with the code.
#
#   ./Scripts/localize.sh
#
# The keys are the Spanish texts in the code. The Swift compiler lists every one of them (with
# its exact format: %@, %lld…); this script then:
#   1. rewrites Resources/Localization/es.lproj/Localizable.strings (each key maps to itself,
#      so Spanish never falls back to English);
#   2. checks that en.lproj/Localizable.strings has every key, with the same placeholders, and
#      lists the ones that are missing or no longer used.
# It fails when a translation is missing, so it can run before a release.
set -euo pipefail

cd "$(dirname "$0")/.."
OUT="$(mktemp -d)"
trap 'rm -rf "$OUT"' EXIT

swift build -Xswiftc -emit-localized-strings -Xswiftc -emit-localized-strings-path -Xswiftc "$OUT" >/dev/null

python3 - "$OUT" Resources/Localization <<'PY'
import glob, json, re, sys
from pathlib import Path

out, root = sys.argv[1], Path(sys.argv[2])
keys = set()
for path in glob.glob(f"{out}/*.stringsdata"):
    for items in json.load(open(path))["tables"].values():
        keys.update(item["key"] for item in items)

def escape(text):
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")

def parse(path):
    table = {}
    pattern = re.compile(r'^"((?:[^"\\]|\\.)*)"\s*=\s*"((?:[^"\\]|\\.)*)";\s*$')
    for line in path.read_text(encoding="utf-8").splitlines():
        match = pattern.match(line)
        if match:
            unescape = lambda s: s.replace('\\"', '"').replace("\\n", "\n").replace("\\\\", "\\")
            table[unescape(match.group(1))] = unescape(match.group(2))
    return table

header = "/* Generated by Scripts/localize.sh: Spanish keys map to themselves. Don't edit. */\n\n"
es = root / "es.lproj" / "Localizable.strings"
es.parent.mkdir(parents=True, exist_ok=True)
es.write_text(header + "".join(f'"{escape(k)}" = "{escape(k)}";\n' for k in sorted(keys)), encoding="utf-8")

en = parse(root / "en.lproj" / "Localizable.strings")
placeholders = lambda s: sorted(re.findall(r"%(?:\d+\$)?(?:lld|ld|d|@|lf|f)", s))
missing = sorted(keys - en.keys())
stale = sorted(en.keys() - keys)
mismatched = sorted(k for k in keys & en.keys() if placeholders(k) != placeholders(en[k]))

print(f"{len(keys)} keys · es.lproj rewritten")
for title, items in (("Missing in en.lproj", missing), ("Placeholders differ", mismatched), ("No longer used", stale)):
    if items:
        print(f"\n{title}:")
        for item in items:
            print(f"  {item!r}")
sys.exit(1 if missing or mismatched else 0)
PY
